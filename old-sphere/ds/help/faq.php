Для начала предлагаю построить 1 кузницу кадериума, 1 нанокристаллизатор и парус уловитель. Рекомендую строить кадериумные кузницы и нанокристаллизаторы по краям соты справа и слева соответственно, но не рассосредотачивайте эти здания где попало, их понадобится много, ведь в будущем, почти всю вашу соту будут занимать производственные здания по добыче различных ресурсов и порядок среди их размещения будет весьма кстати, кроме того удобнее будет вставлять артефакты, по мере их нахождения, ведь здания будут стоять в ряд и вы всегда будете помнить в какое последнее вставили артефакт.<br />
