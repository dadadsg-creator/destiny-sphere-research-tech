- Чтобы узнать открыты ли ворота у вашей будущей цели введите номер соты и комплекса, переключивших на комплекс с помощью блока навигации, нажмите кнопку поиска снизу и комплекс вашего противника предстанет перед вами. Если ворота открыты то они показаны синим цвнтом, есмли же нет, то как-бы надломленны.<br />
