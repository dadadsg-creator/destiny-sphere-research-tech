<span style="font-weight: bold;">б)</span> После того как вы спрятали ресурсы позаботьтесь о своей армии, вы можете отправить ее либо грабить, либо на защиту соты соседа, или же соальянсовика, либо так же спрятать в коннектор, но самый удобный способ это отправить её в укрытие соответствующей командой из военной базы.<br />

<br />
<span style="font-weight: bold;">в)</span> Вы можете активировать силовой щит, правда это вариант для самых ленивых.<br />
<br />
<span style="color: red;">2.</span> Если рейтинг равен или меньше вашего, то можно попробовать встретить, для этого:<br />
<br />
<span style="font-weight: bold;">а)</span> Приведите все ваши войска в боевую готовность, лучше всего слить в одну внутреннюю армию, не забывайте про прослой, ударную группу и грузовоеприкрытие. Излишки или же прокладочную армию (та где вы храните вашу прокладку) укройте. Подготовьте несколько фабрик 1 левела и 2-ого для постройки динамической прослойки.<br />
После вторжения на соту оцените силы врага и действуйте согласно обстоятельствам.<br />

<br />
