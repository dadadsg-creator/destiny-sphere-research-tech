Обычно, и это не для никого не секрет, нападают на игроков с заведомо низким рейтингом, что последних очень раздражает, но ничего с этим не поделать, вам тоже придется этим занятся для получения ресурсов. Для нападения с целью получения ресурсов следует выбирать ближайших соседей в пределах 20-30 комплексов, в определении неактивных игроков (их обычно называют мертвяки или кормушки) вам очень поможет анализатор.<br />
<br />
В Сфере Судьбы существуют 4 определения для 3 типов армий:<br />
<br />
<span style="color: red;">1.Одиночная Боевая</span>- основная армия с полным прослоем и ударной группой, пример такой армии был выше в отчете.<br />

<br />
<span style="color: red;">2. Прокладовыносительная</span> - армия, посылаемая перед боевой с полным прослоем с небольшим количеством мощных юнитов (обычно количество строго рассчитанно на основе даных разведки) для уничтожения прослоя врага в его армии.<br />
<br />
<span style="color: red;">3. Спам/Разведка</span>- армия в размере 1 юнита, служащая для разведки на соте противника. Она заменяет шпионаж и помогает разведать ситуацию на вражеской соте. 1 юнит завязывает секундный бой с обороняющийся армией и в отчете о сражении вы сможете посмотреть состав армии противника, если он, конечно, не спрятал её. <br />
<br />
<span style="color: rgb(255, 0, 0);">4. Волновая Боевая</span> - это даже не название армии а тип атаки, когда множество боевых армий отсылаются в течении тридцати секунд или минуты. Смыл в том, что имея точные сведения о размере армии на соте противника, вычисляется волновая атака, т.е первая армия уничтожит N-ное количество сил противника за один раунд, вторая, уже расчитанная на то, что первая уничтожит часть армии, комплектуется с учетом того, чтобы зацепить на один раунд то, что осталось, по такому принципу и строится волновая атака. Это страшная вещь, потому что, как только первая армия зацепляется, далее идет цепная реакция, и если вас нет на соте, то в считанные часы вы можете потерять всё. Таким образом уничтожаются целые многомиллиардные армады. Такие операции как правило требуют точнейшего расчета и подкарауливание жертвы. Новичка так мучить, никому в голову не взбредет.<br />
