Для успешного ведения боевых действий вам необходимо знать следующие определения:<br />
<br />
<span style="color: red;">Прокладка/Прослой</span> - это выставление в армии групп по 1 юниту разных типов для уменьшения повреждений. Как работает? Вы выставляете: <br />
