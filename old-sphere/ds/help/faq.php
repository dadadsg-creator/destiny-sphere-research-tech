- Раунд битвы в Сфере Судьбы динамический. Длина раунда зависит от соотношения участвующих армий, чем соотношение участвующих армий (отношение бОльшей армии к мЕньшей в проде) меньше, тем короче раунд. <br />
<br />
- Реальный просчет потерь происходит в конце раунда. Каждый раунд просчитывается именно в момент своего протекания. Например, если на соту напали две армии одна в 15.00 другая в 15.10. То сперва обсчитается удар первой&hellip; И в первом раунде она уничтожит половину войск, вторая армия будет сражаться через 10 мин уже с половиной войск оставшимися после первого раунда и уничтожит например половину от того что осталось. Т.е во втором раунде первая армия уже будет биться с четвертью от начального объема ..и т.п. Грабить начнет тот, кто первый добьется победы.<br />
<br />
- Бой происходит автоматически.<br />
<br />
- Вы не можете управлять армией, которая послана атаковать соту противника, возможно только отменить атаку или отступить.<br />

<br />
- Все защищающиеся армии (вне зависимости от принадлежности) перед боем складываются в одну мега армию. Как юниты получают повреждения? К примеру: <br />
У нас есть 3 армии по 10 патриархов. Они случайным образом тасуются и выстраиваются пол порядку &ndash; первая, вторая и третья. У нас наносится удар &ndash; по силе равный убийству 15 пап. Что будет? Первая армия погибнет полностью, так как удар &laquo;сквозной&raquo; во второй погибнет 5 пап. Третья останется не тронутой. <br />
<br />
- Можно выбирать скорость перемещения армии. <br />
Скорость меняется от 50% до 150%. Но хотим Вас успокоить. Скорость увеличивается не сразу. Армия постепенно разгоняется. Так что эффект от разгона Вы увидите только через 3-5-7 комплексов от себя. Таким образом, минимальное время атаки (около 2х часов) не меняется.<br />

<br />
- Время движения происходит из расчета того, что мир состоит из колец, а не из рельс. <br />
Наш мир кольцо. Поэтому, затраты на перемещение между 1 и последним комплексом кольца, будут такими же как между двумя обычными соседними кольцами. Кроме этого, при отправке армий в атаку автоматически выбирается меньший путь до цели (по кольцу). <br />
<br />
- Противники не будет сражаться друг с другом если одновременно армии разных игроков вторгнуться на вашу соту.<br />
<br />
- При отмене атаки и обороны ресурсы, затраченные на дорогу, возвращаются только по возвращению армии, а не сразу при нажатии отмены. В случае если Вы отменили атаку или защиту соты соседа. Неиспользованная часть продуктов взятых на апкип армии будет возвращена. Но только после возврата Вашей армии на базу.<br />
