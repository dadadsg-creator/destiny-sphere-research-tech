- С армией которая вас защищает сделать ничего нельзя, она будет сражаться на вашей соте при атаке на вас, если она вас раздражает то напишите ее хозяину письмо с просьбой отзыва. Реквизиты хозяина можно увидеть в этой армии.<br />
