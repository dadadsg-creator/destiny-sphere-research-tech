<span style="font-weight: bold;"><span style="font-size: 155%; line-height: normal;">2. Открытие Центральных Ворот (ЦВ) и получение продиума</span></span><br />
<br />
Допустим, вы уже построили производственную базу (добывающие здания) и изучили некоторое количество уровней всех наук. Пришло время открывать ворота и начинать взаимодействовать с окружающим миром. Открытие Центральных Ворот сопряжено со множеством опасностей, но плюсов гораздо больше. До открытия ЦВ можно и даже нужно построить армию, например 5-10к юнитов 1 уровня и прослойку. Юниты на первых парах производятся, путем вкладывания в них избыточных ресурсов.<br />
Рекомендуемый уровень наук должен быть 9 для того, чтобы открыть ворота.<br />
<br />

Ремонт ЦВ занимает 72 часа и он считаеться как строительство здания. После ремонта ЦВ по-умолчанию будут открыты, вы сможете в любой момент деактивировать их. Деактивация как и последующая возможная активация занимает 24 часа.<br />
Для ремонта необходимы следующие уровни наук:<br />
<br />
Кадериум уровень 5 <br />
Нанокристаллы  3 <br />
Статическая энергия  3 <br />
Еда  3 <br />
<br />
Построеное здание кадериумный пресс<br />
<br />

Ресурсы: Кадериум 4000 <br />
Нано Кристаллы 1500 <br />
Статическая энергия 4000 <br />
<br />
Не должно протекать строительство максимального количества зданий, т.к ремонт также считается строительством.<br />
<br />
Как только все требования будут выполнены, нажмите на &quot;Развалины Ворот&quot; там появится кнопка апгрейда. Нажмите на нее, и процесс востановления ворот начнётся.<br />
<br />
<span style="color: rgb(255, 0, 0);"><span style="font-weight: bold;">Первым делом после открытия ЦВ вы должны изучить науку Продиум 2 уровня, подгадайте починку ЦВ с окончанием изучения науки, которой на данный момент заняты ваши ученые и приступайте.<br />

После изучения 2 уровня продиума вы наконец-то сможете построить коллектор продиума в центральной соте, и он начнет добывать для вас продиум. Для того чтобы перейти в центральную соту нажмите в блоке навигации кнопку &quot;Центр&quot;.</span></span><br />
<br />
<span style="color: red;">ВНИМАНИЕ:</span> Сборщики продиума потребялют очень много энергии, будъте бдительны.<br />
Теперь, после истчения некоторого времени, у вас имется долгожданный продиум, целесообазно приступить к постройке:<br />
Нагреватель материи(Воранер), Преобразователь материи (Лиенсу), Призма (Псолао).<br />
Далее можно наконец-то строить источники или колодцы с последующим апгрейдом, кому как нравится.<br />
<br />
<span style="color: red;">ВНИМАНИЕ:</span> Если вы начнете деактивировать ворота, а у вас в центральной соте строятся здания, то если они не достроились, они исчезнут, как только ворота деактивируются. <br />

После закрытия ворот все здания, находящиеся в центральной соте, деактивируются автоматически и не приносят дохода.<br />
<br />
<span style="font-weight: bold;">Теперь после открытия ворот вы под защитой новичков, что это такое читайте в следующем пункте.</span><br />
