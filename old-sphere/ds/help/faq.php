Создать альянс проще простого, необходимо зайти в посольство, набрать название вашего альянса (придумывается) и пароль для входа, после этого вы станете лидером альянса.<br />
Если вы до сих пор читаете этот FAQ, то я бы порекомендовал вам вступить в средний альянс и спокойно там развиться до необходимого уровня, накапливая опыт.<br />

