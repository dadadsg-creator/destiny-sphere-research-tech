<span style="font-weight: bold;"><span style="font-size: 155%; line-height: normal;">6. Уровни торговли и сопутствующие им возможности</span></span><br />
<br />
Торговля-важный экономический фактор в Сфере Судьбы с её помощью можно очень выгодно наживать игровое имущество и практиковать свои экономические способности. Это способ обмена ресурсами, юнитами, артефактами за игровую валюту или на вышеперечисленные блага. За каждую торговую операцию взымается налог в пользу Сферы Судьбы, все как в настоящей жизни.<br />
<br />
<span style="font-weight: bold;">Итак, первое что необходимо сделать, это изучить науку Торговля в научном центре. Максимальный уровень изучения может быть 10.</span><br />
<br />

Уровень 2: Дает возможность строить локальный коннектор торговли, торговать статической энергией. <br />
Уровень 3: Дает возможность торговать едой. <br />
Уровень 4: Дает возможность торговать кадериумом. <br />
Уровень 5: Дает возможность торговать нано-кристаллами. <br />
Уровень 6: Дает возможность строить внутрикольцевой коннектор. <br />
Уровень 7: Дает возможность торговать продиумом. <br />
Уровень 8: Дает возможность торговать военными юнитами. <br />
Уровень 9: Дает возможность торговать артефактами. <br />
Уровень 10: Дает возможность строить межкольцевой коннектор. <br />

<br />
<span style="color: red;">ВНИМАНИЕ :</span> Изучение 6 и более уровней торговли будет доступно только после открытия ЦВ (центральных ворот), изучение 10 уровня будет доступно после постройки МКВ (Межкольцевых ворот).<br />
</p>
