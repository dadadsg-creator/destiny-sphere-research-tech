<span style="font-weight: bold;"><span style="font-size: 155%; line-height: normal;"><a name="6.1. Коннекторы Торговли"></a>6.1. Коннекторы Торговли</span></span><br />
<br />
<strong>Первым</strong> вы сможете построить <span style="text-decoration: underline;">Локальный коннектор торговли</span> (ЛКТ) ЛКТ дает возможность торговать внутри вашего комплекса с любым соседом.<br />

<br />
Здание полезно на начальных стадиях игры, для обмена ресурсами - взаимной помощи или помощи односторонней (т.е, например, развитый игрок, если он находится в вашем комплексе, может, если хорошо попросите, бесплатно подарить вам некоторое количество ресурсов) Кроме того, если вас атакуют, вы сможете спрятать в конектор ваши ресурсы, путем выставления их по завышенной цене на нужное время, и тем самым уберечь их от разграбления.<br />
<br />
<strong>Вторым</strong>  вы сможете построить<span style="text-decoration: underline;"> Внутрикольцеовй коннектор торговли (ВКТ)</span> ВКТ дает возможность торговли со всеми игроками внутри вашего родного кольца.<br />
<br />
Абсолютно незаменим в мирах раса против расы и совершенно бесполезен в мирах все против всех, т.к торголвя там идет исключительно на межкольце.<br />
<br />
<strong>Третьим</strong>  и последним вы сможете построить <span style="text-decoration: underline;">Межкольцевой коннектор торговли (МКТ/МККТ)</span>. МКТ дает возможность торговать с двумя другими кольцами, кроме того, если вы член альянса, то торговать внутри альянса на альянсовом аукционе (АА). АА - это зона защищенная от других игроков, аукцион могут просматривать и выставлять на него товары только члены альянса.<br />

<br />
МКТ откроет вам широкие возможности такие как:<br />
<br />
- возможность покупки/выгодного обмена ресурсов у других рас в обмен на вашу продукцию<br />
- возможность покупки юнитов других рас<br />
- возможность торговли артефактами со все сферой<br />
- возможность получать товары с учетом альянсовой скидки.<br />
<br />
Однако, если вы находитесь в сфере раса против расы, вы не сможете покупать ресурсы и юниты у других рас, в таких мирах МКТ используется для торговли в альянсе, а для основной торговли используется Внутрикольцевой Конектор Торговли.<br />
</p>
