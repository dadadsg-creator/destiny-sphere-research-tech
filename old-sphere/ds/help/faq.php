<span style="font-weight: bold;"><span style="font-size: 155%; line-height: normal;"><a name="7.6. Военные артефакты"></a>7.6. Военные артефакты</span></span><br />
<br />
Найденные вами в центральной соте <span style="color: red;">военные артефакты помогут вам  обороняться, но они действуют только на домашней соте</span>, будучи вставленными в военную базу.<br />
Военные артефакты делятся на 4 вида. <br />
<br />
Артефакты атаки: Увеличивают процент попадания. <br />
Артефакты защиты: Увеличивают процент уклонения. <br />
Артефакты урона: Увеличивают урон наносимый вашими юнитами в бою. <br />

Артефакты запаса здоровья: Увеличивают количество &quot;Единиц жизни&quot; ваших юнитов.<br />
<br />
<img src="http://ds.rambler.ru/img/tanker/help/wararts.JPG" alt="Изображение" /><br />
<br />
Артефакты в хранилище не работают, но во время боя можно менять набор артефактов на базе. Действуют на все защищающиеся войска (в том числе на войска других игроков). На атакующую армию артефактовые бонусы не действуют.<br />
Военные артефакты дают определенный % к тому или иному параметру военного юнита. Действует регрессивная система начисления военных бонусов (проценты). На 1 вид артефактов &ndash; защиту &ndash; введена регрессивная система начисления бонусов. Что это такое? <br />
К примеру, у нас 10 артефактов на защиту по 10%. Регрессия считается по разнице между 95% защиты и защитой юнита. При установке в базу каждый следующий артефакт будет давать меньшую защиту, чем предыдущий. Таким образом если защита 75% у юнита, то 10% артефакт защиты ему даст всего 2% прироста. Если у юнита 25% защиты, получается примерно 7% прироста. <br />

<br />
<span style="font-weight: bold;">Если Вы не в ладах с математикой и не хотите возится с расчетами усвойте следующее: каждый следующий военный артефакт вставленный в здание дает меньшую прибавку к параметрам.</span><br />
