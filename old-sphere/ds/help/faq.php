<br />
<span style="font-weight: bold;"><span style="font-size: 155%; line-height: normal;"><a name="1.7. Изучение науки"></a>1.7. Изучение науки</span></span><br />
<br />
Научный центр, который вы сможете построить одним из первых - это важнейшее здание для развития соты. Каждый центр вмещает 500 ученых, которых, в нём же можно и тренировать за нанокристаллы. Постарайтесь построить 1 научный центр как можно быстрее и закажите там тренировать штук 10 ученых, как только 1 ученый будет готов, (время обучения = 6 минутам) вы сможете начать изучать одну из наук:<br />
<br />
<span style="font-weight: bold;">- Кадериум</span> (наука, необходимая для развития соты - строительства новых зданий, юнитов, каждый новый уровень дает бонус к производству)<br />

<br />
<span style="font-weight: bold;">- Нанокристаллы</span> (наука, необходимая для развития соты - строительства новых зданий, юнитов, каждый новый уровень дает бонус к производству)<br />
<br />
<span style="font-weight: bold;">- Статическая Энергия</span> (наука, необходимая для развития соты - строительства новых зданий, юнитов, каждый новый уровень дает бонус к производству)<br />
<br />
<span style="font-weight: bold;">- Продиум</span> ((наука, необходимая для высокотехнологичного развития соты - строительства новых зданий, юнитов, каждый новый уровень дает бонус к производству)(доступен для изучения только после починки и открытия обломков ворот)<br />
<br />
<span style="font-weight: bold;">- Еда</span> (наука, необходимая для развития соты - строительства новых зданий, юнитов, каждый новый уровень дает бонус к производству)<br />

<br />
<span style="font-weight: bold;">- Торговля</span> (каждый новый уровень дает возможность продажи одного из ресурсов или строительства одного из трех торговых зданий- конекторов)<br />
<br />
<span style="font-weight: bold;">- Шпионаж</span> (пока что только готовится к релизу и не работает. <span style="color: rgb(255, 0, 0);">Изучение этой науки и строительство зданий, связанных с ней, - пустая трата времени ресурсов и драгоценного места</span>)<br />
<br />
Не изучая науку, вы никогда не сможете продвинуться в развитии, построить новые здания, проапгрейдить старые и будете стоять на месте, только активно, изучая науку и тренируя больше ученых, вы сможете эффективно застроить соту и натренировать армию.<br />
Следует заметить, что каждый новый уровень науки дольше по времени исследования чем предыдущий, так например, если 100 ученых могли изучить 1 уровень кадериума за 10 минут, 10 -ый уровень они же будут учить месяца два. Поэтому стройте больше научных центров их должно быть порядка 20 штук, для содержания 10000 ученых. Только в таком количестве они смогут эффективно изучать высокие уровни.<br />

<br />
<span style="color: red;">ВНИМАНИЕ:</span> независмо от того сколько у вас научных центров, вы сможете изучать только 1 науку.<br />
<br />
<span style="font-weight: bold;">Зеленая строчка</span> означает % который начисляеться за каждый новый уровень исследования.<br />
<span style="font-weight: bold;">Синяя строчка</span> показывает общий % который вы набрали изучив ту или иную дисциплину.<br />
<br />
Важно помнить, что чем больше ученых тем быстрее изучаеться та или иная дисциплина, поэтому старайтесь, чтобы тренировка ученых велась без перерыва. На начальных этапах игры это довольно сложно , но после постройки достаточного кол-ва добывающих зданий эта проблема отпадет.<br />

Также хочу напомнить, что если вы не знаете требований к зданию вы можете посмотреть их в обзоре зданий на главной странице.<br />
