- При вашей победе на соте противника вы сможете разграбить ресурсы , которые скопились у него, грабить ресурсы позволяет наличие транспорта.Вы сможете разграбить те ресурсы которые вы указали приоритетными когда отправляли армию, если же нет, то грабеж соты происходит всех ресурсов равномерно. Т.е, если у противника недостаточно транспорта, он не сможет вывезти все ваши ресурсы или какой-либо один полностью.<br />
