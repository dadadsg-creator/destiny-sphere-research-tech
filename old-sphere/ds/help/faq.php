<span style="font-weight: bold;"><span style="font-size: 155%; line-height: normal;"><a name="1.6. Деактивация зданий"></a>1.6. Деактивация зданий</span></span><br />
<br />
Если вам временно не нужно какое либо здание, имеет смысл не разрушать его а деактивировать. Кнопка для этого находится под кнопкой &quot;Снести&quot;. <img src="http://ds.rambler.ru/img/tanker/deactivation.JPG" alt="Изображение" /><br />
Здание перестает работать и потреблять энергию, а позже его можно включить снова. Это тоже займет некоторе время, но вам не придется снова тратить ресурсы на постройку.<br />
Кнопка деактивации некоторых зданий находится в закладке &quot;Информация&quot;. Она используется очень редко, но может пригодится...например к вам летит заведомо сильная армия, а на соте отрицательный баланс энергии (это выгодно, так как позволяет производить больше кадериума или нано)...в результате нападения, если вас ограбят энергии станет 0 и здания деактивируются случайным образом, при этом могут деактивироваться и здания производящие юнитов, продукция в них автоматически отмениться, а это иногда бывает весьма болезненно, в этом случае можно деактивировать здания до атаки по своему выбору, также бывает нужно деактивировать здания для выравнивания баланса энергии при неправильной застройке соты, так как лучше самому выбрать, что и как отключить.<br />

В деактивированных зданиях локальные артефакты не работают и вынуть их из деактивированного здания также нельзя.<br />
При отрицательном балансе энергии стоит держать на соте пару хороших артефактов на энергию, это позволит вам в случае нападения оперативно сделать баланс энергии положительным.<br />
