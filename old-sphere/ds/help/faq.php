Если вы не переедете сами то через указанный срок (пишется в письме) вы будете автоматически перемещены.<br />
<br />
2) <span style="font-style: italic;">принудительный переезд</span>, если вы не вошли ни в какой топ то спустя примерно 90 дней вас перенесут автоматом, или же удалят если ваша сота неактивна.<br />
