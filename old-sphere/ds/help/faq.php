а) Первым делом зайдите в военную базу в обзор сражений, там вы увидете бой, который протекает на даным момент, его можно пролистать до текущего раунда, либо визуально с картинкой, либо в виде лога, для определения степени опасности.<br />
<br />
б) Если предполагаемый исход сражения вас не устраивает, вы сможете отступить, нажав соответствующую кнопку там же в обзоре сражений. После активации режима отступления в данном раунде ваша армия не нанесет повреждения, и останется на + 1 раунд в котором также не нанесет повреждений, противник нанесет двойные повреждения и на этом бой закончится.<br />
<br />
<span style="color: red;">Нестандартные ситуации:</span><br />
Если вы только что зашли на соту и увидели, что через минуту к вам прибудет армия захватчика то первым делом укрывайте ваши армии, после этого прячьте самые необходимые ресурсы (нанокристаллы, продиум, кадериум), в принципе, можно успеть спрятать все.<br />
