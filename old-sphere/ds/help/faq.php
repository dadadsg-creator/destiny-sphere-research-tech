Каждый Воин обладает стоимостью. Например, Послушник Псолао. Если мы посчитаем стоимость Послушника, в переводе на энергию, он будет стоить 1950 единиц энергии.<br />
<br />
Для одного Послушника будет взято:<br />
На содержание &ndash; суммарный апкип:1950*0,00005= 0,0975. И в пересчете на каждый ресурс:<br />

В еде будет взято 0,04875 и в энергии будет взято 0,04875.<br />
На трансфер будет затрачено 0,195 энергии<br />
На полет будет затрачено 0,975 энергии.<br />
<br />
Если вам не хватит ресурсов на содержание войск, ваша армия начнет умирать. Умирая, она будет возвращать вам 75% ресурсов.<br />
<br />
Как рассчитывается апкип:<br />
<br />
1. Сначала считаются все ресурсы на соте, учитывается производство на соте, поступившие торговые сделки и т.д.<br />
<br />
2. Оплачивается стоимость фабрик и заводов на соте.<br />

Если у вас не хватило энергии на содержание зданий они отключаются в следующем порядке:<br />
&bull; Здания, производящие ресурсы. Первыми отключаются огромные фабрики, потом большие, потом маленькие фабрики производящие продиум, нано, кадериум.<br />
&bull; Военные здания. Первыми отключаются огромные заводы, затем второй уровень, затем первый.<br />
&bull; Отключаются все оставшееся здания и фермы.<br />
Хотим заметить, что такой порядок сделан для уменьшения вреда для игроков, активно производящих войска.<br />
<br />
3. Оплачивается содержание персонала на соте. В персонал входят:<br />
&bull; Рабочие<br />

&bull; Ученые<br />
&bull; Археологи<br />
<font color="#ff0000">ВНИМАНИЕ:</font> В случае малейшей нехватки еды, они умирают <strong>ВСЕ СРАЗУ</strong>. На существование одного человека тратится 0,2 еды в час.<br />
<br />
4. Далее умирает армия. Т.е. если вам не хватает ресурсов на оплату содержания армии, в дело вступит <strong>следующий механизм.</strong><br />
&bull; Определяется нехватка содержания для армии.<br />

&bull; Сумма нехватки делится на 5 частей.<br />
&bull; Сначала в армии умирает 1/5 часть юнитов от суммы необходимой для покрытия нехватки (Внимание НЕ от армии, а только от суммы нехватки). При этом соблюдаются следующие условия:<br />
- Умирает часть каждой группы юнитов, начиная с первого уровня (4-ый последний) и меньшей группы. Умирает 20% - от суммы недостачи.<br />
- После смерти каждой группы из ресурсов, на которые разложился юнит, выбирается энергия и еда, и пускается на содержание.<br />
&bull; Подводится баланс потребления. Если нам по-прежнему не хватает ресурсов, умирает следующая часть воинов.<br />
В среднем, в игре, благодаря такому циклу, умирает гораздо меньше юнитов, чем могло бы.<br />
<br />
Пример: У нас 5 групп юнитов в армии:<br />

- 1 Солдат<br />
- 1 Гренадер<br />
- 10000 Анимист<br />
- 5000 Гладиатор<br />
- 1000 Патриарх.<br />
Вся армия при апкипе 0,00005 потребляет в час 8358 еды и 8358 энергии. Нам, например, на эту армию не хватает 1000 еды. Т.е. у нас не хватает примерно 6% для содержания армии. Мы делим эту сумму на 5 частей (по 1,2%). Далее, начинаем убивать (начиная с солдата, округляя до ЦЕЛОГО юнита) по 1,2% от группы. Начинаем &laquo;убивать&raquo;<br />
Погиб солдат (округление). Дал нам 60 еды<br />
Погиб гренадер (округление). Дал нам 60 еды.<br />

Погибло 1,2% от  Анимистов (а не 6% сразу) Дали нам 36000 еды.<br />
Анимисты дали сумму достаточную для покрытия нехватки. Далее юниты (Гладиатор и Патриарх) не умирают.<br />
<br />
Если у вас вывезут все ресурсы при нападении:<br />
<br />
У вас на соте сохранятся ресурсы, в размере хранилищ. Но это не все. Армия, находясь на соте &laquo;защищает&raquo; себе содержание в еде и энергии на 24 часа существования (в сумме с хранилищами). Поэтому, если вас ограбили, у вас есть сутки для принятия мер по обеспечению запасов армии.<br />
