<p><br />
<span style="font-weight: bold;"><span style="font-size: 155%; line-height: normal;"><a name="1.4. Апгрейд зданий"></a>1.4. Апгрейд зданий</span></span><br />
<br />
Вначале вы столкнетесь с нехваткой ресурсов, но это неизбежно, со временем, по мере строительства производственных зданий, будет значительно лучше.<br />
Некоторые из построенных вами зданий можно &quot;апгрейдить&quot;- превратить в здание того же типа, но с улучшенными характеристиками.В основном это касается производственных зданий. Апгрейд стоит 80% от общей стоимости конечного здания. В каждом здании есть значок вопроса, и если нажать на него вы увидете описание здания, если здание может в будущем быть преобразовано, вы увидите требования.<br />

<br />
Это касается зданий производящих ресурсы : <br />
<br />
Парус уловитель &gt; Лес парусов <br />
Плантация &gt; Ферма &gt; Ферма Клонов<br />
Жилой дом &gt; Деревня &gt; Город <br />

Нанокристаллизатор &gt; Большой нанокристаллизатор &gt; Огромный нанокристаллизатор<br />
Кузница кадериума &gt; Большая кузница кадериума &gt; Огромная кузница кадериума<br />
Коллектор продиума &gt; Большой коллектор продиума<br />
