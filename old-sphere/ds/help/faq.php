<span style="font-weight: bold;">Первый</span> случай возникает, когда стоимость Своей Армии&trade; в 5 и более раз выше стоимости армии противника. Ваша армия побеждает и с трофеями возвращается домой. <br />
<br />
<span style="font-weight: bold;">Второй</span> случай возникает, когда стоимость Своей Армии&trade; выше в 2 и более раза, чем стоимость армии противника, но не более чем в 5 раз. В таком случае после первого раунда бой заканчивается, вы грабите соту и возвращаетесь. ЛИБО если стоимость армии защитника более чем в 2 раза выше стоимости вашей армии. В таком случае вы проиграете и возвращаетесь домой. <br />
<br />
<span style="font-weight: bold;">Третий</span> случай возникает, когда стоимость любой из армий не более чем в 2 раза выше стоимости другой. И тут уже бой будет вестись до тех пор, пока в один прекрасный момент (после n-го раунда) стоимость одной из армий не превысит стоимость другой более чем в 2 раза. А стоимости, как собственно и урон, считаются в конце раунда. Если после n-го раунда ваша армия более чем в 2 раза будет дороже армии противника - вы грабите и возвращаетесь с трофеями.<br />

