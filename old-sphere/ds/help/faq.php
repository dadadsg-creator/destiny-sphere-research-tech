<span style="font-weight: bold;"><span style="font-size: 155%; line-height: normal;"><a name="2.1. Основные моменты защиты новичков"></a>2.1. Основные моменты защиты новичков</span></span><br />
<br />
Залог успешного развития в любой игре - время. Мы предоставляем некоторое количество времени, в течении которого вы будете полноценно развиваться и находиться под защитой после открытия Центральных Ворот, но есть и определенные условия.<br />
<br />
1. Временное ограничение (после открытия сотовых ворот). Игрок имеет полную защиту от нападений не более 3х недель (21 день). Время может варьироваться в будующем. Игрок лишается защиты автоматически через 3 недели.<br />

<br />
2. Ограничение на размер армии. Игрок, превысивший размер армии в 7* (7 звезд) теряет защиту.  <br />
<br />
3. Ограничение на вступление в альянс. Игрок, вступивший или сформировавший альянс, лишается защиты. При этом он обязан подтвердить решение на вступление или создание альянса. <br />
4. Ограничение на ведение боевых действий в начале игры. Полный запрет на боевые действия. В случае атаки игрок получает предупреждение, что защита с него будет снята. Если он отказывается от атаки - защита сохраняется. Если атакует - снимается навсегда. <br />
<br />
5. Ограничение на покупку и строительство военных юнитов<br />
<br />
6. Обычный игрок не может &quot;защищать&quot; юниора.<br />

<br />
7. Статус новичка отражается на виде комплекса.<br />
