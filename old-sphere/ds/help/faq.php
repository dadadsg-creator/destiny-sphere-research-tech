<span style="color: lime;">Q:</span> Где мне раздобыть юниты других расс для прокладки?<br />
<span style="color: orange;">A:</span> Необходимо либо договорится с кем-нибудь, либо покупать эти юниты после постройки МКТ на межкольцевом аукционе, либо в альянсе. В мирах раса против расы вы не сможете их получить.<br />
<br />
<span style="color: lime;">Q:</span> После апгрейда здания, что будет с артефактом в этом здании? <br />
<span style="color: orange;">A:</span> Он остнеться на своем месте.<br />

<br />
<span style="color: lime;">Q:</span> Я на соте построил монолит, но не могу там создавать оракулов и потриархов. пожалуста оьясните, почему?<br />
<span style="color: orange;">A:</span> Для этого необходимы более высокие уровни науки, сверьтесь по ссылке юнитов.<br />
<br />
<span style="color: lime;">Q:</span> И все же какая армия считаеться оптимальной при открытии ворот?<br />
<span style="color: orange;">A:</span> Запомните золотое правило - армия должна строится непрерывно.<br />

<br />
<span style="color: lime;">Q:</span> Где все-таки выцепить csv-файлы?<br />
<span style="color: orange;">A:</span> <a href="http://ds-game.ru/ds/csv/ranking_%D1%F4%E5%F0%E0%20%C4%F0%E0%EA%EE%ED%E0%20%281-%E9%20%F3%F0%EE%E2%E5%ED%FC%29.csv.gz" class="postlink">Сфера Дракона (1-й уровень)</a><br />
