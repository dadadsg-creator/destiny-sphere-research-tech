- Предупреждение о нападении вы получите сражу же как только армия противника вылетит на вашу соту.<br />
<br />
- Построив несколько военных фабрик, вы сможете в каждой из них тренировать юниты таким образом строительство армии будет во много раз быстрее.</p>

