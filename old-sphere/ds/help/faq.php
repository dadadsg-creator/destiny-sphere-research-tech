<br />
<span style="color: lime;">Q:</span> Если мои соседи по соте неактивны, то я всегда буду один в комплексе? Могут ли эти соты занять другие игроки?<br />

<span style="color: orange;">A:</span> Да если они в течении месяца не зайдут на свои соты, то автоматически удалятся и их место займут новые люди.<br />
<br />
<span style="color: lime;">Q:</span> Бесплатна ли передача ресурсов между колонией и базой?<br />
<span style="color: orange;">A:</span> Ресурсы тратятся только за трансфер армии, посчитать затраты можно встроеным калькулятором в КЦ.<br />
<br />
<span style="color: lime;">Q:</span> Что лучше: сразу сделать побольше сборщиков энергии или дождаться конца исследований для колодца/источника?<br />

<span style="color: orange;">A:</span> Для начала надо застроить весь песок , а затем, если все же будет не хватать энергии построить паруса на земле с последующим их сносом.<br />
<br />
<span style="color: lime;">Q:</span> А правда что администрация может удалить любое здание ?<br />
<span style="color: orange;">A:</span> Да, но это платная услуга. 100р.<br />
<br />
<span style="color: lime;">Q:</span> Помогите я захожу в игру а мне вместо проверки плагина flash пишут DB-connection failed что мне делать?<br />

<span style="color: orange;">A:</span> Это значит , что игра на данный момент не доступна, почитайте новости, возможно причина отключения указана именно в них. Если же нет, то просто наберитесь терпения.<br />
<br />
<span style="color: lime;">Q:</span> Начисляются ли очки за удачные атаки? и отнимаются, если грабят тебя и убивают твоих юнитов?<br />
<span style="color: orange;">A:</span> Да, очки будут отображаться в военном рейтинге.</p>
<p><span style="color: lime;">Q:</span> Какова форума производства ресурсов?<br />

<span style="color: orange;">A:</span> производство = производство_за_ход + абсолютный_бонус + ( производство_за_ход ) * процентный_бонус</p>
<p>где: <strong>абсолютный бонус</strong> - локальные артефакты; <strong>процентный бонус</strong> - религия, бонус расы, сотовые альянсовые комплексные арты, бонусы от науки.</p>
