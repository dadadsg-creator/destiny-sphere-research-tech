Апгрейд здания занимает меньше времени и ресурсов чем постройка нового здания, во время апгрйда здание не произвходит ресурсов, но потребляет энергию. Рано или поздно его нужно будет сделать всем первичным зданиям, из за ограниченности места. <br />
<br />
Для того чтобы апргейдить здание нужно нажать на него. <br />
Справа, возле кнопки сноса вы увидите кнопку с нарисованным молотком. <img src="http://ds.rambler.ru/img/tanker/upgrade.JPG" alt="Изображение" /><br />
Нажмите на неё и апгрейд начнется. <br />
<span style="color: red;"><span style="font-weight: bold;">Перед апгрейдом внимательно проверьте наличия всех необходимых ресурсов/рабочих и не строится ли у вас максимальное количество зданий, т.к апгрейд считается за строительство.</span></span><br />
