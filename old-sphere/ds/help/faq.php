<span style="font-weight: bold;">Важно помнить несколько золотых правил:</span><br />
<br />
1. Энергия никогда не должна быть в минусе на начальных этапах строительства, поэтому следите за этим, подстраивая паруса уловители, по мере потребления зданиями энергии.<br />

<br />
2. Чем лучше здание тем больше энергии оно потребляет.<br />
<br />
3. Когда вы приступите к тренировке ученых и археологов они начнут потреблять еду, каждый человек, будь то рабочий, ученый или археолог потребляют 0.2 еды ежечасно на свое содержание, поэтому важно следить также за положительным показателем и этого ресурса, иначе после того как все запасы еды на вашей соте закончатся, а прирост будет в минусе , население, археологи и ученые и рабочие начнут умирать.<br />
<br />
4. Как бы вы не застроили соту в будущем её придеться перестраивать или терраформировать.<br />
