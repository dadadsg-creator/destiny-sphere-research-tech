<span style="font-weight: bold;"><span style="font-size: 155%; line-height: normal;"><a name="4.4. Некоторые особенности археологии"></a>4.4. Некоторые особенности археологии</span></span><br />
<br />
Теоретически и 1 археолог может принести огромный артефакт.<br />
Никакого вреда не будет, если вы в начале игры попытаетесь найти хоть что-либо послав в экспедицию 10-20 археологов, шанс есть всегда и, быть может, вам повезет.<br />
<br />
Если произойдет деактивация ворот, а ваши археологи, находятся в экспедиции в центральную/нейтральную соту, то они всё равно вернутся по прошествии отведенного времени, более того, если у вас в нейтральной соте имеется некоторое кол-во археологов, то они будут плюсоваться к археологам, живущим в домашней соте, если ворота закрыты.<br />
<br />
Артефакты на ваших сотах и колониях никогда не кончатся, поэтому искать можно хоть всю жизнь.<br />
<br />
Если вы долгое время не можете найти ничего ценного, то вам просто не везет, не отчаивайтесь. Со временем вы обязательно найдете что-нибудь ценное.<br />
<br />

Количество возможных экспедиций ограниченно числом 300</p>
