2. подав заявку (для того чтобы подать заявку, необходимо выбрать какой альянс вам по душе, для этого зайдите в раздел форума вашей сферы, например Сфера Тельца. Далее читайте топики о разных альянсах и подавайте заявку в один из них, если что-то пришлось по душе. Пример как подать заявку обычно опубликован в первом посте топика. Её рассмотрят там же на форуме, и в зависимости от результата, сообщат вам пароль для входа в альянс или же откажут.. Не забывайте заходить на страничку и проверять удовлетворена ли ваша заявка или же нет.<br />
<br />
3. по рекомендации (к примеру, сосед в вашем комплексе уже состоит в альянсе, и вы с ним общаетесь уже некоторое время, если вы захотите, то можете просить о протекции для принятия в альянс, а сосед в свою очередь поговорит с лидерами о вашем принятии.)<br />
<br />
<br />
В каждом случае если решение о вашем принятии будет положительным, вы получите пароль от альянса. Построив в нейтральной соте посольство и зайдя в него, выберите из списка требуемое сокращение альянса введите пароль и нажмите кнопку вступить, с этого момента вы - член альянса. Не забудьте, что альянс это не только брать, но и отдавать. Эффективная отдача от каждого члена альянса - залог интересной и насыщенной игры.<br />
