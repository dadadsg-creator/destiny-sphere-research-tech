<span style="font-weight: bold;"><span style="font-size: 150%; line-height: normal;"><a name="4. Знакомство с археологией"></a>Всё об археологии и артефактах</span></span><br />
<br />
<span style="font-weight: bold;">В этом разделе вы узнаете для чего нужны археологи, что такое артефакты, как их найти и использовать.</span><br />

<br />
<span style="font-weight: bold;"><span style="font-size: 155%; line-height: normal;">4. Знакомство с археологией</span></span><br />
<br />
Знакомство с археологией стоит начать с археологического института. Это здание позволяет вести поиск артефактов в разных частях вашей соты (домашней центральной и нейтральной). <br />
Для начала, разберем, что такое артефакты. Артефакты - это древние реликвии, оставленные конструкторами колец, которые вам предстоит найти с помощью ваших археологов в разных частях вашей соты. Артефакты - мощнейший игровой аспект. Они могут коллосально увеличить могущество их обладателя, конечно, чем больше артефакт тем он дороже и тем сложнее археологам его найти. На форумных аукционах, огромные артефакты могут достигать в цене десятков тысяч юнитов высшего уровня.<br />
<br />
Каждый институт вмещает 500 археологов, которых, в нём же можно и тренировать за кадериум. Пока вы находитесь за закрытми воротами вы сможете искать артефакты только в домашней соте (сотовые и локальные), после открытия ЦВ у вас появиться возможность посылать археологов в экспедицию в центральную соту (за военными артефактами) и в нейтральную (за альянсовыми и комплексными артефактами).<br />
