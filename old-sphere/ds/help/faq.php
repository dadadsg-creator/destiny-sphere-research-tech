Нажмите на здание которое вы хотите разрушить. Вы увидите кнопку &quot;Снести&quot;. <img src="http://ds.rambler.ru/img/tanker/delete.JPG" alt="Изображение" /><br />
Нажмите на нее и здание будет уничтожено. В некоторых зданиях, таких как научный центр, археологический институт и некоторых других, при первом нажатии вы попадаете в другое меню. Нажмите на кнопку &quot;Информация&quot; и вы попадете в нужное меню. Теперь можно и сносить. <br />
Существуют уникальные здания - их сносить невозможно. После постройки такое здание останется с вами навсегда. Будьте внимательны и проверяйте полную информацию о том здании которое вы собираетесь строить. <br />

