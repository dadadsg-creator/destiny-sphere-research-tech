У каждой из трех рас есть возможность строить дополнительный вид улучшенного здания на один из ресурсов. Таким образом возможен апгрейд: <br />
Ферма &gt; Ферма Клонов, Большая Кузница Кадериума &gt; Огромная Кузница Кадериума, Большой Нанокристаллизатор &gt; Огромный нанокристаллизатор <span style="font-weight: bold;">(Лиенсу)</span> <br />

Большая Кузница Кадериума  &gt; Огромная Кузница Кадериума <span style="font-weight: bold;">(Воранеры)</span> <br />
Большой Нанокристаллизатор &gt; Огромный нанокристаллизатор <span style="font-weight: bold;">(Псолао)</span> <br />
<br />
<span style="color: rgb(255, 0, 0);">ВНИМАНИЕ:</span><br />
1 Расовые ограничения на строительство - Только Лиенсу могут строить города. Для Воранеров, максимально возможное здание - деревня, а Псолао приходится ограничиватся жилыми домами. <br />

