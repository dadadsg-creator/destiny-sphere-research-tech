<span style="font-weight: bold;"><span style="font-size: 155%; line-height: normal;"><a name="4.3. Что делать с найденным артефактом"></a>4.3. Что делать с найденным артефактом</span></span><br />
<br />
Для начала надо посмотреть какое название у найденного артефакта.Археологический институт имеет хранилище артефактов, поэтому, если ваши археологи нашли артефакт, он автоматически окажется в хранилище. Зайдя в хранилище, вы сможете просмотреть найденные артефакты, но помещать их можно только из меню зданий. Артефакты по умолчанию выстраиваются сверху вниз (от локальных к альянсовым) и снизу вверх (от крох к огромным) вы можете использовать различные фильтры доступные в хранилище для удобной сортировки.<br />
<br />
<span style="font-weight: bold;">Артефакты деляться на следующие категории:</span><br />
<br />
<br />
<span style="color: rgb(255, 64, 0);">Локальные:</span> Дают добавку к производству соотвествующего ресурса. Вставляются в здания - производители. Их можно найти в Домашней соте. <br />
<br />

<span style="color: rgb(255, 64, 0);">Сотовые:</span> Дают процентный бонус к общему производству ресурсов на соте. Вставляются в Башню Артефактов. Их можно найти в Домашней соте. <br />
<br />
<span style="color: rgb(255, 64, 0);">Комплексные:</span> Дают процентный бонус к общему производству ресурсов на всех шести сотах сотового комплекса. Эти артефакты помогают вам и вашим соседям по комплексу. Вставляются в Башню Артефактов. Их можно найти в Нейтральной Соте. <br />
<br />
<span style="color: rgb(255, 64, 0);">Альянсовые:</span> Дают процентный бонус к общему производству ресурсов на всех сотах членов вашего альянса. Имея такие артефакты вы станете ценным приобретением для любого альянса. Вставляются в Башню Артефактов. Их можно найти в Нейтральной Соте. <br />
<br />
<span style="color: rgb(255, 64, 0);">Военные:</span> Дают разнообразные бонусы к силе армии. Вставляются в Военную Базу. Их можно найти в Центральной соте. <br />

<br />
<span style="color: rgb(255, 64, 0);">Сферы:</span> Дают очень большой бонус до 1000 к производству соответствующего ресурса. Вставляются в здания - производители. Их невозможно найти, но можно получить за победу в турнирах или квестах.<br />
<br />
<span style="color: rgb(255, 64, 0);">Серебрянные/Золотые:</span> Дают существенно больший процентный бонус к общему производству ресурсов на соте чем обычные сотовые артефакты. Вставляются в Башню Артефактов. Их невозможно найти, но можно получить за победу в турнирах или квестах. Один из таких отображен в примере башни артефактов (с черными точками кадериум +20%)<br />
<br />
Чтобы вставить артефакт в здание , необходимо нажать на него и выбрать закладку &quot;Артефакты&quot;, эту закладку имеет каждое производственное здание, после этого, нажав на любой свободный слот/кружок (количество слотов для каждого здания ограничено и зависит от его типа, их может быть от 1 до 4), выбрать из предложенного списка необходимый вам артефакт и нажать кнопоку &quot;вставить&quot;.<br />

Чтобы вставить артефакт в башню артефактов, просто нажмите на нее и вставьте артефакт (если он сотовый/альянсовый/комплексный) в любое свободное окошко.<br />
<br />
<span style="color: red;">ВНИМАНИЕ:</span><br />
Ваши археологи могут принести вам артефакт к <span style="color: olive;">продиуму</span> либо локальный либо сотовый. Если на этот момент у вас закрыты ворота , то локальный артефакт не может быть использован, сотовый можно вставить в башню артефактов , но толку он не принесет. Вам придеться подождать до открытия ворот и после постройки коллектора продиума поместить туда артефакт, либо в башню артефактов если он сотовый.<br />
<br />
<span style="font-weight: bold;">Только будучи помещенным в здание, артефакт начнет приносить доход и добавлять очки в рейтинг.</span><br />
