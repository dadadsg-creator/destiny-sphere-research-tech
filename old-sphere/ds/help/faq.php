Уметь обороняться особенно важно! Не всегда можно встретить противника лицом к лицу и принять честный бой, к примеру под плотным спамом, угадать какая из армий боевая просто не возможно, к счастью по началу вы не будете подвергаться серьезным нападениям, целю которых уничтожение вашей армии. Поначалу это будут обычные армии для ограбления соты с минимум юнитов.<br />

