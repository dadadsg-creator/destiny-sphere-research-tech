<span style="font-weight: bold;"><span style="font-size: 155%; line-height: normal;"><a name="3.3. Жизнь нейтралом"></a>3.3. Жизнь нейтралом</span></span><br />

<br />
Состояние нейтрала это состояние, когда игрок не вступает ни в один альянс в течении долгого времени, из принципа или по одному ему ведомым причинам. В любом случае, опасность стать целью для кого-нибудь возрастает многократно. Быть нейтралом вполне реально, но необходимо быть очень активным игроком и практически постоянно находится в игре, так называемое 24/7 (24 часа, 7 дней в неделю)<br />
Плюсов в таком состоянии, прямо скажем не мало, к некоторым из них можно отнести полную свободу действий, отсутствие налогообложения, нестандартные пути развития соты для самодостаточности. Но, одной из важнейших особенностей для нейтрала одиночки является высокий рейтинг.<br />
</p>
<hr width="100%" size="2" />
<p><br />
<br />
<span style="font-weight: bold;"><span style="font-size: 155%; line-height: normal;"><a name="3.4. Понятие рейтинга и механизм его начисления"></a>3.4. Понятие рейтинга и механизм  его начисления</span></span><br />
<br />
В Сфере Судьбы рейтинг игроков подобен вашему компасу во многих тысячах сот. Существует два вида рейтинга:<br />
<br />
<span style="font-weight: bold;">Обычный Рейтинг.</span><br />

<br />
Посмотреть рейтинг возможно, нажав соответствующую кнопку вверху экрана соты.<br />
Перед вам появиться таблица, вы видите N-ную страницу игрового рейтинга вашей сферы и где-то на ней выделен ваш игровой ник, напротив которого находяться определенные цифры, они и составляют ваш игровой рейтинг. Чем ближе вы к первой странице тем лучше, тем больше вас будут опасаться более слабые и уважать более сильные игроки.<br />
Этот рейтинг считаеться следующим образом:<br />
Вычисляются средние значения всех игроков по параметрам - наука, строительство, производство, археология и армии, среднее значение получает 100.000 очков (армия 200.000 очков).<br />
Для каждого игрока вычисляется по каждому из параметров насколько он лучше или хуже чем средний игрок. Если например у игрока X втрое лучше развита наука чем у среднего игрока A, он получает 300.000 пунктов за развитие науки, зато если у него (игрока X) производство слаборазвито и составляет 50% от среднего значения, он получает 50.000 очков за эту категорию. В рейтинге археологии учитываются только реально используемые артефакты, а не все которые лежат в хранилище. Если игрок развивается лучше чем в среднем, его пункты растут, если хуже - падают. <br />
Наличие квестовых артефактов (их можно получить в приз, став победителем одного из квестов на вашей сфере) существенно увеличивает рейтинг.<br />
<br />
<span style="font-weight: bold;">Военный рейтинг.</span> <br />

<br />
Этот рейтинг ведет учет всех ваших сражений, он считается просто по весу убитых юнитов. Убил на 1 000 000 прода, получил 1 рейта. Убил на 2 000 000, получил 2. Если на защите было несколько армий, то между их владельцами делится согласно отношению весов их армий. полезность этого рейтинга очевидна - можно видеть насколько игрок активный боец.<br />
<br />
<span style="color: red;">ВНИМАНИЕ:</span> Именно обоими рейтингами вы должны руководствоваться при нападении и обороне своей соты, об этом читайте в разделе военных действий.<br />
</p>
