<span style="font-weight: bold;">Если на вас нападают не нервничайте, все предельно просто:</span><br />
<br />
<span style="color: red;">1.</span> Сравните рейтинг нападающего, если он гораздо больше вашего то:<br />
<br />
<span style="font-weight: bold;">а)</span> Прячьте ресурсы, это означает, что вы должны выставить все ресурсы, которыми располагаете на продажу в любой коннектор торговли, который у вас есть на <span style="font-weight: bold;">собственное имя</span>. Выставляйте по цене равной кол-ву выставляемого ресурса. Конечно, для возможности выставления всех ресурсов у вас должна быть изучена торговля хотя бы до 7 уровня. Если торговли не хватает то есть смысл вложить ресурсы в постройку юнитов.<br />
