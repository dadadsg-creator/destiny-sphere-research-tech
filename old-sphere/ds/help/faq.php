Создавать свой альянс имеет смысл игроку, который уже познакомился с игрой и имеет приличный багаж знаний о ней, таких как: стратегическое планирование боевых операций, дипломатия, экономика, развитие новичков и прочие тонкости управления кадрами.<br />
