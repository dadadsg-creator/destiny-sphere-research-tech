<span style="font-weight: bold;"><span style="font-size: 155%; line-height: normal;"><a name="4.1. Количество археологов в группе на экспедицию"></a>4.1. Количество археологов в группе на экспедицию</span></span><br />

<br />
Поиск артефактов - целая наука, немало игроков потратили уйму времени, пытаясь раскрыть секрет формулы поисков артефактов. Но скажу по секрету, что даже если вы узнаете формулу, это не даст вам ровным счетом ничего, так как поиск всегда рандомен, однако есть определенные числа, выработанные и проверенные временем, которые оптимальны для поисков. <br />
<br />
<span style="font-weight: bold;">Для  относительно успешных экспедиций число археологов в каждой экспедиции должно быть примерно следующее:</span><br />
<br />
- 2000-3000 в домашную соту по несколько групп, если у вас 10000 археологов, групп будет 5 и т д<br />
<br />
- от 5000 до 15000 в центральную соту<br />
<br />
- не менее 15000 и более в нейтральную соту<br />
<br />
Таким образом для успешных поисков на вашей соте должно быть порядка 25000 археологов. Достигается такое количество строительством институтов на домашней соте и лагерей археологов в нейтральной.<br />

Количество экспедиций не может превышать 300 штук.<br />
<br />
Старайтесь делать так, чтобы экспедиции приходили к тому времени, когда у вас будет возможность отправить археологов на&nbsp; дальнейшие поиски, сразу после их прибытия. Бесцельное простаивание на соте не лучшее занятие для них.<br />
Нахождение хорошего артефакта всегда рандомное и зависит от времени, поэтому советую отправлять ваши экспедиции на минимум на 8 -12 часов.<br />
<br />
<span style="font-style: italic;">Вы можете выбрать какой артефакт должны найти археологи, однако, стоит помнить, что при поиске определённого размера артефакты ниже уровнем удаляются даже если будут найдены, и будет вполне логично, если выбрав огромный или большой для поисков археологи чаще всего будут возвращаться с пустыми руками, такие артефакты редки.</span><br />
