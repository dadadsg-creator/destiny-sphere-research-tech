<span style="font-weight: bold;"><span style="font-size: 150%; line-height: normal;"><a name="5. Получение колоний"></a>Всё о колонизации</span></span><br />
<br />
<span style="font-weight: bold;">В этом разделе вы узнаете  как получить колонии, что это такое и как лучше всего их использовать.</span><br />

<br />
<span style="font-weight: bold;"><span style="font-size: 155%; line-height: normal;">5. Получение колоний</span></span><br />
<br />
Получение колонии это одно из самых главных достижений, ведь, получая колонию, вы сможете обладать еще одной сотой, точно такой же как и ваша домашняя, а это новые площади для застройки, новые производственные мощности, больше ученых археологов, военных юнитов ресурсов.<br />
<br />
Для того чтобы получить колонию необходимо построить КЦ (Колонизационный Центр). <br />
<br />
<span style="color: rgb(255, 0, 0);">ВНИМАНИЕ:</span> Возможность строительства КЦ отключена на первом уровне  Тельца и Дракона. <br />
<br />
Для его постройки необходимы высокие уровни наук:<br />

Кадериум  13 <br />
Нанокристаллы 12 <br />
Статическая Энергия 12 <br />
Продиум  11 <br />
Еда  13 <br />
<br />
Также для постройки КЦ необходимо построенное здание МВ (межкольцевые ворота)<br />
КЦ строится в Центральной Соте, на скале. Его строительство занимает 72 часа и он потребляет 5000 энергии каждый час. <br />
Вам необходимо подготовиться к его постройке, имея запас производимой энергии не менее 7к.<br />

<br />
После построки КЦ вы можете выбрать координаты соты на четвертом кольце Мелсион и отправить колонизационный модуль, для получения колонии.<br />
<br />
Для того , чтобы поселиться подальше от развитых игроков, или если вы просто хотите некоторое время побыть одни в комплексе, пролистайте комплексы на Мелсионе и выберите себе подходящий.<br />
Время передачи ресурсов и прочего в колонию будет минимальным, если вы колонизируете комплекс с идентичным номером вашему домашнему комплексу.<br />
<br />
Существующий способ колонизации, типа: отправка модуля в любую свободную соту, может быть неоправданным, т.к многие альянсы стараються заселиться в 1 комплекс для того, чтобы насладиться в полной мере комплексными артефактами. Ваше случайное заселение в их комплекс не очень обрадует последних.<br />
<br />
После прибытия модуля на вашу новую колонию вы обнаружите , что это такая же сота как и ваша домашняя с одним лишь отличием: <span style="color: red;">ЦВ на колонии уже открыты и закрыть их невозможно!</span><br />
<br />
Наука в колонии является продолжением науки вашей базовой соты. Ученые изучают ту же самую науку, не важно где они находятся. <br />

Археология является автономной, и связать археологов с базовой соты и колонии в одну экспедицию невозможно.<br />
</p>
<hr width="100%" size="2" />
<p><br />
<br />
<span style="font-weight: bold;"><span style="font-size: 155%; line-height: normal;"><a name="5.1. Трансфер"></a>5.1. Трансфер</span></span><br />
<br />
Для облегчения развития новобретенной колонии, вы можете переслать ресурсы с домашней соты в колонию, это осуществляеться путем <span style="text-decoration: underline;">трансфера</span>.<br />
Эта опция доступна в КЦ вы можете выбрать желаемое кол-во ресурсов и переправить на колонию. Помимо ресурсов вы можете отправить ученых, рабочих, археологов, военные юниты и артефакты.</p>
<p> <span style="color: red;">ВНИМАНИЕ:</span> При отправке на колонию ученых/археологов/рабочих обязательно убедитесь, что кол-во отправляемых сответствует наличию свободных мест в колонии, т.е для того чтобы переправить, к примеру, 1000 ученых необходимо, чтобы в колонии были построены 2 научных центра, <span style="text-decoration: underline;">в которых не тренируються ученые.</span><br />

______________________________________________________________________________<br />
<br />
<br />
<span style="font-weight: bold;"><span style="font-size: 155%; line-height: normal;"><a name="5.2. Застройка колонии (вкратце)"></a>5.2. Застройка колонии (вкратце)</span></span><br />
<br />
В колонии нужно строить те же самые здания, что и в домашней соте, просто этот процесс будет быстрым, т.к необходимый уровень наук изучен а ресурсы переправляются.<br />
Соответсвенно центральная и нейтральная сота застраиваеться по подобию домашних.<br />
<br />
Постарайтесь как можно быстрее построить 2 КЦ на колонии, после этого вы сможете получить вторую колонию , она же и будет последней, т.к <span style="text-decoration: underline;">можно иметь не более 2 колоний.</span> <br />
<br />

<span style="color: red;">ВНИМАНИЕ:</span> Для того , чтобы иметь возможность пересылать ресурсы из колонии в домашнюю соту и из колонии в колонию, необходимо иметь КЦ на каждой колонии!<br />
<br />
По желанию вы можете использовать колонии под самые разнообразные нужды, вот некоторые примеры:<br />
<br />
1. Застройка колонии под &quot;свой&quot; ресурс, имеется ввиду строительство только добывающих зданий, например нанокристаллизаторы.<br />
<br />
2. Застройка всей колонии археологами, в итоге после претворения такой идеи, вы сможете отправлять порядка 70к археологов на поиски артефактов.<br />
<br />

3. Застройка колонии научными центрами, для интенсивного изучения необходимой дисциплины, дающей бонус к расовому ресурсу.<br />
<br />
4. Обычное развитие соты.<br />
<br />
5. Застройка колонии военными зданиями, с постоянной пересылкой ресурсов и непрекращающейся тренировкой военных юнитов.<br />
</p>
<hr width="100%" size="2" />
<p><br />
<br />
<br />
<span style="font-weight: bold;"><span style="font-size: 155%; line-height: normal;"><a name="5.3. Застройка колонии. Понятие специализации соты"></a>5.3. Застройка колонии. Понятие специализации соты</span></span><br />
<br />
Здесь пойдет речь о том, какую стратегию большинство игроков выбирает после получения колоний.<br />

<br />
<span style="color: orange;">Специализация соты</span> бывает полная и частичная с положительным и отрицательным балансом энергии.<br />
<br />
Под <span style="color: orange;">полной специализацией</span> обычно понимают строительство максимально возможного количества добывающих зданий для одного типа ресурса, башня с артефактами при этом также заполняется артефактами только на этот ресурс, что позволяет значительно повысить эффективность соты...<br />
<br />
Под <span style="color: orange;">неполной специализацией</span><br />
подразумевается застройка домашней соты зданиями по добыче одного ресурса, в то время как земля в центральной соте остается застроенной коллекторами продиума.<br />

<br />
Также бывает специализация<br />
1) С <span style="color: brown;">неотрицательным балансом энергии </span>- строятся здания по добыче ресурсов и источники для добычи энергии<br />
2) С <span style="color: brown;">отрицательным балансом энергии </span>- в этом случае снесены все источники и вместо них также построены добывающие здания, при помощи хороших локальных артефактов и альянсового бонуса можно добится положительного баланса энергии и без источников, получив максимальную эффективность соты, но это достаточно сложная задача для начинающего игрока.<br />
<br />
<span style="color: red;">ВНИМАНИЕ:</span>минусом полной специализации с отрицательным балансом энергии является возможное отключение большого количества зданий при ограблении соты, подобная специализация встречается у игроков, которые стараются не участвовать в любых военных действиях.<br />
<br />
Выбор специализации чаще всего определяется бонусами расы на добычу ресурсов. Специализация до постройки межкольцевого коннектора торговли малоэффективна так как не позволяет обмениваться ресурсами по нормальным рыночным курсам. Полная специалиация также становится целесообразна на достаточно поздних этапах развития, когда бонус за счет науки и артефактов позволяет добится от зданий по добыче ресурсов большей эффективности чем у большого коллектора продиума.<br />

</p>
<hr width="100%" size="2" />
<p><br />
<br />
<br />
<span style="font-weight: bold;"><span style="font-size: 155%; line-height: normal;"><a name="5.4. Примеры специализаций для всех трех рас"></a>5.4. Примеры специализаций для всех трех рас</span></span><br />
<br />
Расчет делается на то, что у вас уже продвинутый акаунт с двумя колониями, скажу лишь, что на начальном этапе специализация невыгодна в силу того, что уровень наук слишком мал, а артефакты не достаточно качественные, нет конекторов торговли, есть только один способ добычи ресурса &ndash; грабеж, который не всегда приносит желаемый результат. Исходя из этого, в начале соту нужно застраивать так, чтобы добыча ресурсов была, примерно, поровну.<br />
<br />
<span style="font-weight: bold;">Воранеры.</span><br />
Приведем возможные варианты застройки всех 3 сот.<br />

1) С появлением первой колонии производим переброс всех ученых, которые есть на домашке на колонию, предварительно позаботившись о том , чтобы для них были свободные места.(иначе исчезнут)<br />
После переброски ученых начинаем сносить нанокристаллизатры на домашней соте и строить огромные кузницы кадериума, а также сносим продиумные коллекторы , в общем все все на соте, что не относится к кадериумным кузницам , кроме технологическх здании типа нагревателя материи, кадериумного пресса, башни артефактов и т д.<br />
<br />
В итоге у нас получается 102 огромных кадериумных кузницы, а если терраформировать то 132 на соте. Естественно в башне артефактов должны стоять артефакты только на кадериум и энергию для обеспечения всех кузниц.<br />
<br />
Необходимо сразу определится изберет ли вы этот пусть, поскольку если вы строили в нейтральной соте археологические институты то вам понадобятся источники для того, чтобы обеспечить все кузни, а строить их надо вместо кузниц. Та что вы можете либо сразу начать строить паруса уловители в нейтралке, чтобы построить потом больше кузниц, либо арх институты.<br />
Далее перейдем к первой колонии, куда переехали ученые, раз они уже тут то и колония эта будет только под ученых. Заполнять ли ее только учеными ваше личное дело, но бонус от науки которую вы потом изучите с помощью них будет весьма и весьма существенен для добычи большего кол-ва кадериума. Продиумные коллекторы тут строить тоже не стоит поскольку в центре вы тоже сможете построить научные центры.<br />
Вторая колония может быть использована вами подо что угодно, там вы сможете построить коллекторы продиума, ( в этом случае в башне артефактов будут артефакты на продиум и энергию),все застроить военными заводами, можно построить еще ученых или же немного ресусрных зданий или и того и другого и военные заводы, в общем места для фантазии хватит.<br />
<br />
Минусы:<br />

Придется кардинально менять всю домашнюю соту и в чем то себе отказывать, как например, отсутствие продиума некоторое время, переброска ученых/артефактов, малое кол-во археологов(если вы строите паруса в нейтралке). В общем переезд дело тяжкое как в жизни.<br />
Плюсы:<br />
Быстрое получение специализации, возможность торговать в скором времени большими партиями кадериума.<br />
<br />
2) С появлением первой колонии производим переброс всех ученых, которые есть на домашке на колонию, предварительно позаботившись о том , чтобы для них были свободные места.(иначе исчезнут). Свободное место от ученых застраиваем огромными кузницами кадериума, строим больше военных заводов. Нанокристаллизаторы и коллекторы продиума оставляем до лучших времен.<br />
Первую колонию заполняем только учеными и на этом с ней закончим.<br />
После получения второй колонии после постройки выскотехнологичных зданий ( нагреватель материи, кадериумный пресс, башня артефактов и т д), полной застройки пустыни на домашней соте под леса парусов, начинаем застраивать домашку и центр огромными кузницами кадериума, соответсвенно на эту колонию пересылаем все артефакты сотовые и локальные на кадериум.<br />
<br />
Минус:<br />
Слишком долго ждать пока будет большой прирост профилирующего ресурса.<br />

Плюс: <br />
Спокойно отстроившись без бардака добывать кадериум, без перерывов в строительстве армии.<br />
<br />
<span style="font-weight: bold;">Псолао.</span><br />
Для Псолао я бы написал все то же, что и для воранеров. За исключением того, что скорее всего профилирующую соту, а точнее нейтралку необходимо будет застраивать парусами уловителями.<br />
<br />
<span style="font-weight: bold;">Лиенсу.</span><br />
Для Лиенсу, как я считаю, есть 3 способа:<br />
1) После получения первой колони, начинать застраивать ее под кадериум.<br />
После получения второй колонии застраивать ее под нано.<br />

Домашнюю соту можно приспособить под продиум, ученых и военные заводы.<br />
<br />
Плюс: Стабильный приход ресурсов, неплохой бонус и порядок везде.<br />
Минус: Неполная застройка соты учеными<br />
<br />
2) После получения первой колони, начинать застраивать ее под кадериум, строить так же ученых, продиум, военные заводы<br />
После получения второй колонии застраивать ее под нано, строить так же ученых, продиум, военные заводы<br />
Домашнюю соту можно приспособить под ученых немного ресурсов и военные заводы<br />
<br />
Плюс: Равномерное распределение ученых и военных заводов<br />

Минус: Бонус от добычи будет меньше за счет постройки продиума, ученых и военных заводов.<br />
<br />
3) После получения первой колони, начинать застраивать ее под кадериум, строить так же ученых, продиум.<br />
После получения второй колонии застраивать ее под нано, строить так же ученых, продиум.<br />
Домашнюю соту можно приспособить равное кол-во ресурсов кадериум/нано/продиум и военные заводы.<br />
<br />
Плюс: Неплохой баланс прироста ресурсов на всех трех сотах<br />
Минус: Бонус будет не так велик как мог бы быть без ученых.<br />
<br />
На каждой колонии для Лиенсу вы может строить археологические институты только в нейтральной соте, дабы добывать больше еды, можете добывать много еды на паре колоний или всего на одной соте, в зависимотси сколько археологов и еды вы хотели бы у себя видеть.<br />

<br />
<span style="color: rgb(255, 0, 0);">ВНИМАНИЕ:</span> Все вышеописанные способы специализаций сот для трех рас, только лишь мое мнение, скомпилированное на основе личного игрового опыта всеми тремя расами и статистики от других игроков, вы совершенно не обязаны делать так как здесь описано, а можете избрать свой путь развития, однако, вышеприведенные схемы - классические.<br />
</p>
