			$ch->set_attribute ( "id_message", $res[$i]['id_message'] );
			$ch->set_attribute ( "id_from_user", $res[$i]['id_from_userinstance'] );
			$ch->set_attribute ( "from_user", $res[$i]['from_user'] );
			$ch->set_attribute ( "messagedate", $res[$i]['messagedate'] );

			$res[$i]['subject'] = str_replace("[","",$res[$i]['subject']);
			$res[$i]['subject'] = str_replace("]","",$res[$i]['subject']);
			$res[$i]['subject'] = str_replace("%","?",$res[$i]['subject']);
			$res[$i]['subject'] = str_replace("&","?",$res[$i]['subject']);

			$ch->set_attribute ( "subject", urlencode ( str_replace("\"", "", str_replace("'","",$res[$i]['subject']) ) ) );
			$ch->set_attribute ( "scopename", $res[$i]['messagescopename'] );
			$ch->set_attribute ( "lscopename", urlencode ( $res[$i]['localizedmessagescope'] ) );

			$messageText = trim($res[$i]['messagetext']);
			
/*$messageText = "????? ???????? ??????? ??????????? ????, ? ????? ???????. ? ??????? ??????, ????? ????? ????????? ???????? ? ????????? ??? - ????? ??????? ???. ????? ??????? ???????? ? ????????, ???????, ?????? ? ????????? ? ????? ??????????? ? ????????? ????? ?? ???? ?? ???????? ?? ????? ??????. 
