http://forum.destinysphere.ru/forum/viewtopic.php?t=155407
?????????? ????? ?? ?????, ???????? ? ???????? ???????????. ?????? ????????? ???????.
";*/
			
			$messageText = str_replace("[", "", $messageText);
			$messageText = str_replace("]", "", $messageText);
			$messageText = str_replace("'", "", $messageText);
			$messageText = str_replace("\"", "", $messageText);			
			$messageText = str_replace("&", "?", $messageText);
			$messageText = urlencode($messageText);
			
			
			//$elem = $doc->create_text_node ( urlencode ( trim ( $res[$i]['messagetext'] ) ) );
			$elem = $doc->create_cdata_section($messageText);
			$ch->append_child($elem);
		}

		// отмечаем что они прочитаны
		$table = array('','reserv');
		foreach ($table as $key => $value)
			{
