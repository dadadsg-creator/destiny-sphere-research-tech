						$params["uiid"] );

				$res = $common->executeQuery ( $sql );

				if ( $res === false ) {
					$this->errormsg .= " SYSTEM ERROR MessageOverview::getPanel2";
					return false;
				}
			}

		// закладки
		if ( $this->bid != "" )
		{
