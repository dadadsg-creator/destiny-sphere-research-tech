	function getPanel ()
	{
		global $params;
		global $common;

		$delta = DE_User::CreateFromID((int)$_SESSION['uid'])->getTimeDelta();

		$xml = '<?xml version="1.0" encoding="utf-8"'."?"."><messageoverview />";
		$doc = domxml_open_mem ( $xml );
		$root = $doc->document_element ();
		$root->set_attribute ( "c", $this->id_cell );

		// извлекаем все мессаги
		$sql = sprintf ( "
				SELECT
      				out.id_message,
      				out.readdate,
      				out.id_from_userinstance,
				  	out.from_user,
	  				out.messagedate,
	  				out.dateforsort,
	  				out.subject,
	  				out.messagetext,
	  				out.messagescopename,
	  				out.localizedmessagescope
FROM
(
				SELECT
					m.id_message,
					uhm.readdate,
					m.id_from_userinstance,
					u.username as from_user,
					to_char ( m.messagedate  + '%f hour'::interval, 'DD.MM HH24:MI') as messagedate,
					m.messagedate as dateforsort,
					m.subject,
					m.messagetext,
					ms.messagescopename,
					ltl.text as localizedmessagescope
				FROM
					ds_userhasmessage uhm,
					ds_message m,
					ds_messagescope ms,
					ds_localizedtextlanguage ltl,
					ds_userinstance ui,
					ds_user u
				WHERE
						uhm.id_message = m.id_message
					AND m.id_messagescope = ms.id_messagescope
					AND ms.id_localizedname = ltl.id_localizedtext
					AND ltl.id_language = %d
					AND uhm.id_userinstance = %d
					AND m.id_from_userinstance = ui.id_userinstance
					AND ui.id_user = u.id_user
				UNION ALL (
					SELECT
						m2.id_message,
						uhm2.readdate,
						m2.id_from_userinstance,
						u2.username as from_user,
						to_char ( m2.messagedate  + '%f hour'::interval, 'DD.MM HH24:MI') as messagedate,
						m2.messagedate as dateforsort,
						m2.subject,
						m2.messagetext,
						ms2.messagescopename,
						ltl2.text as localizedmessagescope
					FROM
						ds_userhasmessagereserv uhm2,
						ds_messagereserv m2,
						ds_messagescope ms2,
						ds_localizedtextlanguage ltl2,
						ds_userinstance ui2,
						ds_user u2
					WHERE
							uhm2.id_message = m2.id_message
						AND m2.id_messagescope = ms2.id_messagescope
						AND ms2.id_localizedname = ltl2.id_localizedtext
						AND ltl2.id_language = %d
						AND uhm2.id_userinstance = %d
						AND m2.id_from_userinstance = ui2.id_userinstance
						AND ui2.id_user = u2.id_user
					)) as out
					ORDER BY out.dateforsort DESC",
				$delta,
				$params["lang"],
				$params["uiid"],
				$delta,
				$params["lang"],
				$params["uiid"] );
//error_log($sql, 3, '!Test.log');
		$res = $common->getResultArray ( "userhasmessage_language_userinstance_".$params["lang"]."_".$params["uiid"], $sql, "", $params["uiid"], "LOCAL_CACHE" );

		if ( $res === false ) {
			$this->errormsg .= " SYSTEM ERROR MessageOverview::getPanel1";
			return false;
		}

		// запихиваем все это в xml
		for ( $i=0; $i<sizeof ( $res ); $i++ ) {

/*
